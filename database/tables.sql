-- ============================================================================
-- 1. BOOKS TABLE
-- Stores catalogued books with physical inventory copy counters.
-- ============================================================================
CREATE TABLE BOOKS (
    book_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    title            VARCHAR2(200)               NOT NULL,
    author           VARCHAR2(150)               NOT NULL,
    isbn             VARCHAR2(25)                NOT NULL,
    category         VARCHAR2(60)                NOT NULL,
    total_copies     NUMBER(4)     DEFAULT 1     NOT NULL,
    available_copies NUMBER(4)     DEFAULT 1     NOT NULL,
    created_at       DATE          DEFAULT SYSDATE NOT NULL,
    
    -- Table Constraints
    CONSTRAINT pk_books_id 
        PRIMARY KEY (book_id),
    CONSTRAINT uq_books_isbn 
        UNIQUE (isbn),
    CONSTRAINT chk_books_total_copies 
        CHECK (total_copies >= 1),
    CONSTRAINT chk_books_avail_copies 
        CHECK (available_copies >= 0),
    CONSTRAINT chk_books_avail_le_total 
        CHECK (available_copies <= total_copies)
);

COMMENT ON TABLE BOOKS IS 'Catalogued books and physical inventory copy counts';
COMMENT ON COLUMN BOOKS.book_id IS 'Surrogate primary key generated by Oracle identity';
COMMENT ON COLUMN BOOKS.isbn IS 'Unique International Standard Book Number';
COMMENT ON COLUMN BOOKS.total_copies IS 'Total owned copies of the title';
COMMENT ON COLUMN BOOKS.available_copies IS 'Currently available copies on the shelf';

-- ============================================================================
-- 2. MEMBERS TABLE
-- Stores registered library cardholders eligible to borrow items.
-- ============================================================================
CREATE TABLE MEMBERS (
    member_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    full_name        VARCHAR2(120)               NOT NULL,
    email            VARCHAR2(120)               NOT NULL,
    phone            VARCHAR2(25)                NOT NULL,
    membership_date  DATE          DEFAULT SYSDATE NOT NULL,
    status           VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
    
    -- Table Constraints
    CONSTRAINT pk_members_id 
        PRIMARY KEY (member_id),
    CONSTRAINT uq_members_email 
        UNIQUE (email),
    CONSTRAINT chk_members_status 
        CHECK (status IN ('ACTIVE', 'SUSPENDED', 'INACTIVE'))
);

COMMENT ON TABLE MEMBERS IS 'Registered library patrons/members';
COMMENT ON COLUMN MEMBERS.member_id IS 'Surrogate primary key generated by Oracle identity';
COMMENT ON COLUMN MEMBERS.status IS 'Member standing: ACTIVE, SUSPENDED, INACTIVE';

-- ============================================================================
-- 3. ISSUE_RECORDS TABLE
-- Tracks book borrowing transactions, due dates, returns, and statuses.
-- ============================================================================
CREATE TABLE ISSUE_RECORDS (
    issue_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    book_id          NUMBER                      NOT NULL,
    member_id        NUMBER                      NOT NULL,
    issue_date       DATE          DEFAULT SYSDATE NOT NULL,
    due_date         DATE                        NOT NULL,
    return_date      DATE,
    status           VARCHAR2(20)  DEFAULT 'ISSUED' NOT NULL,
    
    -- Table Constraints
    CONSTRAINT pk_issues_id 
        PRIMARY KEY (issue_id),
    CONSTRAINT fk_issues_book 
        FOREIGN KEY (book_id) 
        REFERENCES BOOKS (book_id) 
        ON DELETE CASCADE,
    CONSTRAINT fk_issues_member 
        FOREIGN KEY (member_id) 
        REFERENCES MEMBERS (member_id) 
        ON DELETE CASCADE,
    CONSTRAINT chk_issues_status 
        CHECK (status IN ('ISSUED', 'RETURNED', 'OVERDUE')),
    CONSTRAINT chk_issues_due_date 
        CHECK (due_date >= issue_date),
    CONSTRAINT chk_issues_return_date 
        CHECK (return_date IS NULL OR return_date >= issue_date)
);

COMMENT ON TABLE ISSUE_RECORDS IS 'Circulation records for borrowed and returned books';
COMMENT ON COLUMN ISSUE_RECORDS.issue_id IS 'Unique transaction record ID';
COMMENT ON COLUMN ISSUE_RECORDS.status IS 'Transaction status: ISSUED, RETURNED, or OVERDUE';

-- ============================================================================
-- 4. PERFORMANCE & FOREIGN KEY INDEXES
-- ============================================================================
CREATE INDEX idx_issues_book_id   ON ISSUE_RECORDS (book_id);
CREATE INDEX idx_issues_member_id ON ISSUE_RECORDS (member_id);
CREATE INDEX idx_issues_status    ON ISSUE_RECORDS (status);
CREATE INDEX idx_books_category   ON BOOKS (category);
CREATE INDEX idx_books_title      ON BOOKS (title);

